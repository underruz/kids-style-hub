// Функция для получения товаров с учетом админ-панели
const getAdminProducts = () => {
  try {
    const adminProducts = localStorage.getItem('littlestyle-admin-products');
    return adminProducts ? JSON.parse(adminProducts) : mockProducts;
  } catch {
    return mockProducts;
  }
};

export const getAllProducts = () => getAdminProducts();
export const getFeaturedProducts = () => getAllProducts().filter(p => p.featured);
export const getCategoryProducts = (category: string) => getAllProducts().filter(p => p.category === category);
export const getNewProducts = () => getAllProducts().filter(p => p.isNew);
export const getSaleProducts = () => getAllProducts().filter(p => p.isSale);
export const getProductById = (id: string) => getAllProducts().find(p => p.id === id);